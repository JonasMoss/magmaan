test_that("ordinary RDWLS composes lab fitting and exact-weight policy", {
  for (mixed in c(FALSE, TRUE)) {
    d <- hs()[paste0("x", 1:6)]
    ordered <- paste0("x", seq_len(if (mixed) 3L else 6L))
    for (v in ordered) d[[v]] <- ordered(cut(d[[v]], 3))
    syntax <- "f =~ x1 + a*x2 + b*x3\ng =~ x4+x5+x6\ng ~ f"
    model <- magmaan_model(syntax, prototype = d, ordered = ordered)
    null <- magmaan_model(paste(syntax, "a == b", sep = "\n"), prototype = d, ordered = ordered)
    fit <- magmaan(model, d, estimator = "RDWLS")
    handle <- magmaanlab::prepare_model(model$spec, prototype = d)
    lab <- magmaanlab::estimate(handle, magmaanlab::prepare_data(handle, d), estimator = "RDWLS")
    configured <- magmaan(model, d, estimator = "RDWLS", options = list(optimizer = "port"))
    expect_identical(configured$estimator, "RDWLS")
    expect_true(all(is.finite(vcov(configured))))
    expect_identical(fit$estimator, "RDWLS")
    expect_equal(fit$lab$theta, lab$theta, tolerance = 1e-10)
    policy <- magmaanlab::policy_inference(lab)
    expect_equal(vcov(fit), policy$covariance, ignore_attr = TRUE, tolerance = 1e-10)
    expect_true(all(is.finite(confint(fit))))
    expect_output(print(fit), "RDWLS.*exact first-stage Gamma weights")
    standardized <- summary(fit, standardized = TRUE)
    expect_true(all(is.finite(standardized$coefficients$std.all)))
    expect_output(print(standardized), "exact first-stage Gamma weights")
    nested <- anova(magmaan(null, d, estimator = "RDWLS"), fit)
    expect_identical(nested$reference[nested$recommended], "all")
    expect_true(all(is.finite(nested$pvalue[nested$recommended])))
    mi <- modindices(fit, candidates = "~~")
    lab_mi <- magmaanlab::policy_modification_indices(lab)
    expect_equal(mi$statistic, lab_mi$statistic[lab_mi$op == "~~"], tolerance = 1e-10)
    for (method in list(infer, vcov, summary, confint, fit_measures))
      expect_error(method(fit, lavaan_compat = "WLSMV"), "RDWLS.*no lavaan estimator")
    default <- magmaan(model, d)
    dwls <- magmaan(model, d, estimator = "DWLS")
    expect_identical(default$estimator, "DWLS")
    expect_equal(default$lab$theta, dwls$lab$theta)
    expect_equal(vcov(default), vcov(dwls))
    d[1, 1] <- NA
    expect_error(magmaan(model, d, estimator = "RDWLS"), "RDWLS requires complete")
  }
  expect_error(magmaan(magmaan_model(cfa), hs(), estimator = "RDWLS"), "RDWLS is for ordered")
})
